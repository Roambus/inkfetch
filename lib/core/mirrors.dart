String _encodePath(String path) => path
    .split('/')
    .map((s) => s.isEmpty ? s : Uri.encodeComponent(s))
    .join('/');

String? _rawPath(ParsedUrl parsed) {
  final owner = parsed.owner;
  final repo = parsed.repo;
  final ref = parsed.gitRef;
  final path = parsed.path;
  if (owner == null || repo == null || ref == null || path == null) {
    return null;
  }
  return '$owner/$repo/${_encodePath(ref)}/${_encodePath(path)}';
}

String? buildMirrorUrl(MirrorSpec spec, ParsedUrl parsed) {
  switch (spec.kind) {
    case MirrorKind.official:
      return parsed.normalized;
    case MirrorKind.codeload:
      if (parsed.kind != UrlKind.archive) return null;
      final owner = parsed.owner;
      final repo = parsed.repo;
      final ref = parsed.gitRef;
      final format = parsed.archiveFormat;
      if (owner == null || repo == null || ref == null || format == null) {
        return null;
      }
      return 'https://codeload.github.com/$owner/$repo/$format/${_encodePath(ref)}';
    case MirrorKind.prefix:
      return '${spec.base}/${parsed.normalized}';
    case MirrorKind.rawHost:
      if (parsed.kind != UrlKind.raw) return null;
      final path = _rawPath(parsed);
      if (path == null) return null;
      return '${spec.base}/$path';
    case MirrorKind.jsDelivr:
      if (parsed.kind != UrlKind.raw) return null;
      final owner = parsed.owner;
      final repo = parsed.repo;
      final ref = parsed.gitRef;
      final path = parsed.path;
      if (owner == null || repo == null || ref == null || path == null) {
        return null;
      }
      if (ref.contains('/')) return null;
      return '${spec.base}/gh/$owner/$repo@${_encodePath(ref)}/${_encodePath(path)}';
    case MirrorKind.statically:
      if (parsed.kind != UrlKind.raw) return null;
      final ref = parsed.gitRef;
      if (ref == null || ref.contains('/')) return null;
      final path = _rawPath(parsed);
      if (path == null) return null;
      return '${spec.base}/gh/$path';
    case MirrorKind.gitHack:
      if (parsed.kind != UrlKind.raw) return null;
      final path = _rawPath(parsed);
      if (path == null) return null;
      return '${spec.base}/$path';
    case MirrorKind.domainReplace:
      if (parsed.kind != UrlKind.release && parsed.kind != UrlKind.archive) {
        return null;
      }
      const officialPrefix = 'https://github.com/';
      if (!parsed.normalized.startsWith(officialPrefix)) return null;
      return 'https://${spec.base}/${parsed.normalized.substring(officialPrefix.length)}';
  }
}

List<SourceCandidate> buildCandidates(
  ParsedUrl parsed,
  List<String> disabledIds,
) {
  final seen = <String>{};
  final output = <SourceCandidate>[];
  for (final spec in builtinMirrors) {
    if (disabledIds.contains(spec.id)) continue;
    if (!spec.supports.contains(parsed.kind)) continue;
    final url = buildMirrorUrl(spec, parsed);
    if (url == null || url.isEmpty) continue;
    if (!seen.add(url)) continue;
    output.add(
      SourceCandidate(
        id: spec.id,
        name: spec.name,
        url: url,
        lane: spec.lane,
        maxConns: spec.maxConns,
        priority: spec.priority,
        experimental: spec.experimental,
      ),
    );
  }
  return output;
}

List<MirrorSpec> get mirrorCatalog => builtinMirrors;
